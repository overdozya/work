/* Optional browser integration check. Requires Playwright and Chrome. */
const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const server=spawn(process.env.PYTHON||'python3',[path.join(__dirname,'browser_server.py')],{cwd:root,stdio:['ignore','pipe','pipe']});
let browser;
(async()=>{
  const port=await new Promise((resolve,reject)=>{server.stdout.once('data',d=>resolve(Number(d.toString().trim())));server.once('error',reject);server.once('exit',code=>reject(new Error(`Test server exited ${code}`)));});
  browser=await chromium.launch({channel:'chrome',headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
  await page.goto(`http://127.0.0.1:${port}`);
  await page.getByRole('heading',{name:'답을 배우지 말고, 판단을 가져오세요.'}).waitFor();
  assert.equal(await page.locator('.case-card').count(),3);
  const shots=path.join(root,'.local','screenshots');fs.mkdirSync(shots,{recursive:true});
  await page.screenshot({path:path.join(shots,'home-desktop.png'),fullPage:true});
  await page.locator('.case-card').first().click();
  await page.getByRole('button',{name:/관찰 단서:/}).click();
  await page.locator('.inspector blockquote').waitFor();
  assert.match(await page.locator('.inspector').innerText(),/시선이 각자 흩어졌습니다/);
  await page.screenshot({path:path.join(shots,'decision-map.png'),fullPage:true});
  await page.locator('[data-nav="training"]').click();
  await page.getByRole('heading',{name:'조건을 흔들어 본 뒤, 연습합니다.'}).waitFor();
  await page.getByRole('button',{name:'조건 바꾸기로 이동 ⇄'}).click();
  await page.getByRole('button',{name:'고정 반례 체험하기 ⇄'}).click();
  await page.locator('input[name="reviewer"]').fill('브라우저 자동화 검증');
  await page.locator('textarea[name="note"]').fill('검증용 예시에서 안내물의 관람 거리와 정보 전달 목적을 확인했습니다.');
  await page.getByRole('button',{name:'검토 기록 저장'}).click();
  await page.locator('input[name="confirmed"]').check();
  await page.getByRole('button',{name:'이 판단을 훈련에 사용하도록 승인 ✓'}).click();
  await page.getByRole('button',{name:'새 상황에서 연습 ↗'}).click();
  await page.getByRole('button',{name:'데모 문제 열기 ↗'}).click();
  await page.getByRole('heading',{name:'전시 포스터가 동네 안내문이 된다면'}).waitFor();
  assert.equal(await page.locator('.hint-box').count(),0);
  await page.getByRole('button',{name:'힌트 한 단계 열기 (0/3)'}).click();
  await page.locator('.hint-box').waitFor();
  await page.locator('input[name="option_id"][value="b"]').check();
  await page.locator('textarea[name="reasoning"]').fill('2m 관람 거리에서 날짜와 장소를 먼저 읽을 수 있는지 확인합니다. 원래 포스터의 긴장감과 안내문의 목적이 다르므로 정보 영역을 묶는 대안과 제목을 키우는 대안을 비교합니다.');
  await page.getByRole('button',{name:'데모 답안 기록하기 ↗'}).click();
  await page.getByRole('heading',{name:'데모 기록 · 스스로 점검하기'}).waitFor();
  assert.equal(await page.locator('.dimension-card').count(),5);
  assert.match(await page.locator('.assessment').innerText(),/데모에서는 답안의 질을 자동 채점하지 않습니다/);
  await page.screenshot({path:path.join(shots,'training-feedback.png'),fullPage:true});
  await page.locator('[data-nav="progress"]').click();
  await page.getByRole('heading',{name:'무엇을 알고, 무엇을 해낼까요?'}).waitFor();
  assert.match(await page.locator('#main').innerText(),/실제 Gemini 훈련 기록이 아직 없습니다/);
  const downloadPromise=page.waitForEvent('download');
  await page.getByRole('button',{name:'실험 기록 내려받기 ↓'}).click();
  const download=await downloadPromise;
  const output=path.join(root,'.local','browser-export.json');await download.saveAs(output);
  const data=JSON.parse(fs.readFileSync(output,'utf8'));
  assert.equal(data.sessions.length,1);
  assert.equal(data.sessions[0].hints_used,1);
  assert.equal(data.sessions[0].origin,'demo');
  assert.ok(data.events.some(e=>e.kind==='knowledge_approved'));
  await page.locator('[data-nav="home"]').click();
  await page.setViewportSize({width:390,height:844});
  await page.goto(`http://127.0.0.1:${port}/#home`);
  await page.locator('.case-card').first().waitFor();
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve))));
  await page.locator('#toast').evaluate(el=>el.classList.remove('visible'));
  await page.screenshot({path:path.join(shots,'home-mobile.png'),fullPage:true});
  for(const route of ['home','map','counterfactual','training','progress']){
    await page.goto(`http://127.0.0.1:${port}/#${route}`);
    await page.locator('#case-select, .case-card').first().waitFor();
    const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,view:window.innerWidth}));
    assert.ok(width.scroll<=width.view+1,`${route}: horizontal overflow ${JSON.stringify(width)}`);
  }
  await page.getByRole('button',{name:'＋ 새 사례 담기'}).click();
  await page.getByRole('dialog').waitFor();
  assert.equal(await page.locator('dialog textarea').count(),1);
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  assert.deepEqual(errors,[]);
  console.log('Browser PASS: source map, approval gate, counterfactual review, hints, submission, demo exclusion, export, five mobile routes, modal, no console errors.');
})().catch(e=>{console.error(e);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.kill('SIGTERM');});
